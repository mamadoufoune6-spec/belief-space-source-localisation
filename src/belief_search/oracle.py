"""Explicit privileged navigation baseline; ordinary controllers are untouched.

Only this runner gives the router the true source coordinates. RSSI is still
generated by the same environment, but no measurement or posterior selects
the oracle's movement. Source localisation is GIVEN, not estimated.
"""

from dataclasses import asdict
from time import perf_counter

import numpy as np

from .radio_control import GridRouter
from .radio_environment import RadioMapEnvironment, RadioEnvironmentConfig


def run_oracle_episode(truth_bank, *, robot_xy, source_id, seed, controller_seed,
                       config=None, router=None, reserve_last_unit=True):
    """Shortest-route true-source baseline under the same physical constraints.

    The current sub-cell success radius means arrival is the true source cell;
    this restriction keeps the reported source-cell shortest distance a valid
    lower bound on attempted moves to success.
    """
    config = config if config is not None else RadioEnvironmentConfig()
    if config.success_radius_m >= 1:
        raise ValueError("This source-cell oracle requires success_radius_m < 1 m")
    if not isinstance(reserve_last_unit, bool):
        raise ValueError("reserve_last_unit must be boolean")
    env = RadioMapEnvironment(truth_bank, config, runner_managed=True)
    observation, evaluation = env.reset(robot_xy=robot_xy, source_id=source_id, seed=seed)
    true_source_xy = tuple(map(int, truth_bank.transmitter_xy[source_id]))
    router = router if router is not None else GridRouter(truth_bank)
    began = perf_counter()
    distances = router.distances_to(true_source_xy)
    preprocessing_ms = (perf_counter() - began) * 1000
    optimal = int(distances[truth_bank.array_index(robot_xy)])
    rng = np.random.default_rng(controller_seed)
    samples, decision_ms = [], []
    used_budget, past_action = 0, None
    command = "initial"
    required = 2 if reserve_last_unit else 1
    began = perf_counter()

    while True:
        remaining = int(distances[truth_bank.array_index(observation.robot_xy)])
        samples.append({"command": command, **asdict(observation),
                        "reached_source": evaluation.reached_source,
                        "remaining_route_steps": remaining, "used_budget": used_budget})
        if evaluation.reached_source:
            stop_reason = "reached"
            break
        if remaining < 0:
            stop_reason = "unreachable_true_source"
            break
        if used_budget >= config.max_steps:
            stop_reason = "budget_exhausted"
            break
        if config.max_steps - used_budget < required:
            stop_reason = "shared_reserve_stop"
            break
        started = perf_counter()
        action = router.action(observation.robot_xy, true_source_xy, past_action, rng)
        decision_ms.append((perf_counter() - started) * 1000)
        if action is None:
            raise RuntimeError("Reachable nonterminal oracle position has no routing action")
        observation, evaluation = env.step(action)
        used_budget += 1
        if not observation.boundary_blocked:
            past_action = action
        command = action.name

    return {"policy": "Oracle", "knowledge": "true_source_position_and_public_geometry",
            "localisation": "given_not_inferred", "truth_simulation": truth_bank.simulation,
            "model_simulation": None, "map_id": truth_bank.map_id,
            "robot_start": tuple(robot_xy), "true_source_id": source_id,
            "true_source_xy": true_source_xy, "sensor_seed": seed,
            "controller_seed": controller_seed, "config": asdict(config),
            "movement_budget_minimum": required, "optimal_steps_to_source": optimal if optimal >= 0 else None,
            "samples": samples, "stop_reason": stop_reason, "reached": evaluation.reached_source,
            "used_budget": used_budget, "movement_attempts": observation.attempt,
            "blocked_attempts": sum(s["boundary_blocked"] for s in samples),
            "observations": len(samples), "decision_ms": decision_ms,
            "route_preprocessing_ms": preprocessing_ms,
            "episode_ms": (perf_counter() - began) * 1000}
